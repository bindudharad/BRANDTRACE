def generate_logo_verification_report(
    analysis_id: str,
    workspace_id: str = "ws_default",
    generated_by: str = "Brand Admin",
    force_recreate: bool = False,
) -> Dict[str, Any]:
    """
    Generates or retrieves a persistent, immutable official logo verification report.
    Returns complete report record with download and verification links.
    """
    # Check if report already exists for this analysis in workspace
    existing = row(
        "SELECT * FROM logo_reports WHERE analysis_id=? AND workspace_id=?",
        (analysis_id, workspace_id),
    )
    if existing and not force_recreate:
        # Check if physical PDF file exists; if not, recreate it from stored snapshot
        pdf_path = Path(existing["pdf_storage_path"]) if existing.get("pdf_storage_path") else get_report_storage_path(workspace_id, existing["id"])
        if not pdf_path.exists():
            # Recreate physical file
            analysis = row("SELECT * FROM logo_analyses WHERE id=? AND workspace_id=?", (analysis_id, workspace_id))
            candidates = rows("SELECT * FROM logo_candidates WHERE analysis_id=? AND workspace_id=? ORDER BY page_number ASC", (analysis_id, workspace_id))
            findings = rows("SELECT * FROM logo_findings WHERE analysis_id=? AND workspace_id=? ORDER BY page_number ASC, severity DESC", (analysis_id, workspace_id))
            
            ref_info = None
            std_info = None
            if existing.get("reference_id"):
                ref_info = get_reference_logo(existing["reference_id"], workspace_id)
                std_info = get_or_create_logo_standard(existing["reference_id"], workspace_id)

            checks_matrix = json.loads(existing.get("checks_json", "[]"))
            pdf_bytes = _build_pdf_document(
                report_meta=existing,
                analysis=analysis or {},
                candidates=candidates,
                findings=findings,
                reference_info=ref_info,
                standards_info=std_info,
                matrix=checks_matrix,
            )
            pdf_path.parent.mkdir(parents=True, exist_ok=True)
            pdf_path.write_bytes(pdf_bytes)

        return _format_report_dict(existing)

    # Load analysis data
    analysis = row(
        "SELECT * FROM logo_analyses WHERE id=? AND workspace_id=?",
        (analysis_id, workspace_id),
    )
    if not analysis:
        raise KeyError(f"Logo analysis '{analysis_id}' not found in workspace '{workspace_id}'.")

    candidates = rows(
        "SELECT * FROM logo_candidates WHERE analysis_id=? AND workspace_id=? ORDER BY page_number ASC",
        (analysis_id, workspace_id),
    )
    findings = rows(
        "SELECT * FROM logo_findings WHERE analysis_id=? AND workspace_id=? ORDER BY page_number ASC, severity DESC",
        (analysis_id, workspace_id),
    )

    # Resolve active reference standards
    ref_info = None
    std_info = None
    ref_id = None
    ref_name = None
    ref_version = None
    standards_version = "v1.0"

    # Attempt to locate reference from candidate or analysis
    matched_ref_ids = [c["matched_reference_id"] for c in candidates if c.get("matched_reference_id")]
    if matched_ref_ids:
        ref_id = matched_ref_ids[0]
    elif analysis.get("reference_versions_used_json"):
        try:
            r_used = json.loads(analysis["reference_versions_used_json"])
            if r_used:
                ref_id = r_used[0].get("id")
        except Exception:
            pass

    if ref_id:
        ref_info = get_reference_logo(ref_id, workspace_id)
        if ref_info:
            ref_name = ref_info.get("name")
            ref_version = ref_info.get("version")
            std_info = get_or_create_logo_standard(ref_id, workspace_id)
            standards_version = f"v{ref_version}" if ref_version else "v1.0"

    # Build compliance results matrix
    matrix = _evaluate_compliance_matrix(
        analysis=analysis,
        candidates=candidates,
        findings=findings,
        reference_info=ref_info,
        standards_info=std_info,
    )

    report_id = ident("lrep")
    created_at = now()
    date_code = datetime.now(timezone.utc).strftime("%Y%m%d")
    unique_suffix = uuid.uuid4().hex[:6].upper()
    report_number = f"BT-RPT-{date_code}-{unique_suffix}"
    filename = f"BRANDTRACE_Logo_Verification_{report_number}.pdf"

    pdf_storage_path = str(get_report_storage_path(workspace_id, report_id))

    source_hash = analysis.get("source_file_hash") or hashlib.sha256(analysis["source_filename"].encode("utf-8")).hexdigest()

    summary_snapshot = {
        "analysis_id": analysis_id,
        "overall_verdict": analysis["overall_verdict"],
        "candidates_count": len(candidates),
        "compliant_count": analysis.get("compliant_candidates", 0),
        "findings_count": len(findings),
        "page_count": analysis.get("page_count", 1),
        "reference_id": ref_id,
        "reference_name": ref_name,
    }

    report_meta = {
        "id": report_id,
        "analysis_id": analysis_id,
        "workspace_id": workspace_id,
        "report_number": report_number,
        "filename": filename,
        "pdf_storage_path": pdf_storage_path,
        "source_filename": analysis["source_filename"],
        "source_file_hash": source_hash,
        "overall_verdict": analysis["overall_verdict"],
        "summary_json": json.dumps(summary_snapshot),
        "checks_json": json.dumps(matrix),
        "findings_count": len(findings),
        "reference_id": ref_id,
        "reference_name": ref_name,
        "reference_version": ref_version,
        "standards_version": standards_version,
        "status": "GENERATED",
        "created_at": created_at,
        "created_by": generated_by,
    }

    # Generate PDF bytes
    pdf_bytes = _build_pdf_document(
        report_meta=report_meta,
        analysis=analysis,
        candidates=candidates,
        findings=findings,
        reference_info=ref_info,
        standards_info=std_info,
        matrix=matrix,
    )

    checksum_sha256 = hashlib.sha256(pdf_bytes).hexdigest()
    report_meta["checksum_sha256"] = checksum_sha256

    # Save physical PDF
    p = Path(pdf_storage_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(pdf_bytes)

    # Persist immutable record in database
    with db() as conn:
        conn.execute(
            """
            INSERT INTO logo_reports (
                id, analysis_id, workspace_id, report_number, filename,
                pdf_storage_path, source_filename, source_file_hash, overall_verdict,
                summary_json, checks_json, findings_count, reference_id,
                reference_name, reference_version, standards_version, checksum_sha256,
                status, created_at, created_by
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                report_id, analysis_id, workspace_id, report_number, filename,
                pdf_storage_path, analysis["source_filename"], source_hash, analysis["overall_verdict"],
                json.dumps(summary_snapshot), json.dumps(matrix), len(findings), ref_id,
                ref_name, ref_version, standards_version, checksum_sha256,
                "GENERATED", created_at, generated_by,
            ),
        )

    audit(
        review_id=analysis_id,
        action="LOGO_REPORT_GENERATED",
        actor=generated_by,
        actor_role="Brand Governance Lead",
        details=json.dumps({
            "report_id": report_id,
            "report_number": report_number,
            "overall_verdict": analysis["overall_verdict"],
            "checksum_sha256": checksum_sha256,
        }),
        workspace_id=workspace_id,
    )

    return _format_report_dict(report_meta)


