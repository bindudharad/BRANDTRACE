def get_logo_report_pdf_bytes(report_id: str, workspace_id: str = "ws_default") -> bytes:
    """Retrieve raw PDF bytes for downloading or streaming."""
    rec = row(
        "SELECT * FROM logo_reports WHERE (id=? OR report_number=?) AND workspace_id=?",
        (report_id, report_id, workspace_id),
    )
    if not rec:
        raise KeyError(f"Report '{report_id}' not found in workspace '{workspace_id}'.")

    pdf_path = Path(rec["pdf_storage_path"]) if rec.get("pdf_storage_path") else get_report_storage_path(workspace_id, rec["id"])
    if pdf_path.exists():
        return pdf_path.read_bytes()

    # Recreate on the fly if physical file was cleared
    analysis = row("SELECT * FROM logo_analyses WHERE id=? AND workspace_id=?", (rec["analysis_id"], workspace_id))
    candidates = rows("SELECT * FROM logo_candidates WHERE analysis_id=? AND workspace_id=? ORDER BY page_number ASC", (rec["analysis_id"], workspace_id))
    findings = rows("SELECT * FROM logo_findings WHERE analysis_id=? AND workspace_id=? ORDER BY page_number ASC, severity DESC", (rec["analysis_id"], workspace_id))
    
    ref_info = None
    std_info = None
    if rec.get("reference_id"):
        ref_info = get_reference_logo(rec["reference_id"], workspace_id)
        std_info = get_or_create_logo_standard(rec["reference_id"], workspace_id)

    checks_matrix = json.loads(rec.get("checks_json", "[]"))
    pdf_bytes = _build_pdf_document(
        report_meta=rec,
        analysis=analysis or {},
        candidates=candidates,
        findings=findings,
        reference_info=ref_info,
        standards_info=std_info,
        matrix=checks_matrix,
    )
    pdf_path.parent.mkdir(parents=True, exist_ok=True)
    pdf_path.write_bytes(pdf_bytes)
    return pdf_bytes


def verify_logo_report_authenticity(report_id: str) -> Dict[str, Any]:
    """
    Public / workspace cryptographic verification endpoint.
    Confirms whether a report was genuinely generated and unaltered.
    """
    rec = row(
        "SELECT * FROM logo_reports WHERE id=? OR report_number=?",
        (report_id, report_id),
    )
    if not rec:
        return {
            "verified": False,
            "report_id": report_id,
            "status": "NOT_FOUND",
            "message": "Report record does not exist in BRANDTRACE Governance Ledger.",
        }

    # Verify physical file hash if file exists
    pdf_path = Path(rec["pdf_storage_path"]) if rec.get("pdf_storage_path") else None
    actual_pdf_hash = None
    file_intact = True
    if pdf_path and pdf_path.exists():
        actual_pdf_hash = hashlib.sha256(pdf_path.read_bytes()).hexdigest()
        file_intact = (actual_pdf_hash == rec["checksum_sha256"])

    return {
        "verified": file_intact,
        "report_id": rec["id"],
        "report_number": rec["report_number"],
        "workspace_id": rec["workspace_id"],
        "analysis_id": rec["analysis_id"],
        "source_filename": rec["source_filename"],
        "source_file_hash": rec["source_file_hash"],
        "overall_verdict": rec["overall_verdict"],
        "checksum_sha256": rec["checksum_sha256"],
        "reference_id": rec.get("reference_id"),
        "reference_name": rec.get("reference_name"),
        "issued_at": rec["created_at"],
        "status": "AUTHENTIC" if file_intact else "TAMPER_DETECTED",
        "governance_authority": "BRANDTRACE Visual Compliance Engine v2.0-LVE",
    }


def list_logo_reports(workspace_id: str = "ws_default") -> List[Dict[str, Any]]:
    """List all generated reports for a workspace, newest first."""
    report_rows = rows(
        "SELECT * FROM logo_reports WHERE workspace_id=? ORDER BY created_at DESC",
        (workspace_id,),
    )
    return [_format_report_dict(r) for r in report_rows]


def _format_report_dict(rec: Dict[str, Any]) -> Dict[str, Any]:
    """Helper to deserialize JSON columns and format URLs."""
    d = dict(rec)
    if isinstance(d.get("summary_json"), str):
        try:
            d["summary"] = json.loads(d["summary_json"])
        except Exception:
            d["summary"] = {}
    elif "summary_json" in d:
        d["summary"] = d.get("summary_json") or {}

    if isinstance(d.get("checks_json"), str):
        try:
            d["checks"] = json.loads(d["checks_json"])
        except Exception:
            d["checks"] = []
    elif "checks_json" in d:
        d["checks"] = d.get("checks_json") or []

    d["download_url"] = f"/api/logo-intelligence/reports/{d['id']}/download"
    d["verify_url"] = f"/api/logo-intelligence/reports/{d['id']}/verify"
    return d
