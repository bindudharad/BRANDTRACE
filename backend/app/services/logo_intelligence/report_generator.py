def _is_check_passed(val: Any) -> bool:
    if val is None:
        return False
    if isinstance(val, dict):
        return bool(val.get("passed", False) or str(val.get("status", "")).upper() in ("COMPLIANT", "APPROVED_MATCH", "PASS"))
    if isinstance(val, str):
        return val.upper() in ("COMPLIANT", "APPROVED_MATCH", "PASS")
    return False


def _is_check_evaluated(val: Any) -> bool:
    if val is None:
        return False
    if isinstance(val, str):
        return val.upper() not in ("NOT_EVALUATED", "SKIPPED", "NONE", "")
    return True


def _evaluate_compliance_matrix(
    analysis: Dict[str, Any],
    candidates: List[Dict[str, Any]],
    findings: List[Dict[str, Any]],
    reference_info: Optional[Dict[str, Any]],
    standards_info: Optional[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """
    Evaluates the 8 core brand visual compliance dimensions.
    Rule: Never convert an unperformed or missing check into a PASS.
    Unperformed checks are strictly marked 'NOT EVALUATED'.
    """
    findings_by_type: Dict[str, List[Dict[str, Any]]] = {}
    for f in findings:
        ft = f.get("finding_type", "")
        findings_by_type.setdefault(ft, []).append(f)

    primary_cand = candidates[0] if candidates else None
    checks_summary: Dict[str, Any] = {}
    if primary_cand and primary_cand.get("checks_summary_json"):
        try:
            checks_summary = json.loads(primary_cand["checks_summary_json"])
        except Exception:
            checks_summary = {}

    has_ref = bool(reference_info and reference_info.get("id"))
    std = standards_info or {}

    matrix = []

    # 1. Identity & Trademark
    if not has_ref:
        matrix.append({
            "dimension": "Identity & Trademark",
            "requirement": "Match registered corporate mark (score >= 70%)",
            "observed": "No registered reference configured in workspace",
            "outcome": "NOT EVALUATED",
        })
    elif "STYLE_MISMATCH" in findings_by_type or "UNRECOGNIZED_MARK" in findings_by_type:
        f_list = findings_by_type.get("STYLE_MISMATCH") or findings_by_type.get("UNRECOGNIZED_MARK") or []
        obs = f_list[0].get("observed_value", "Style mismatch detected") if f_list else "Mismatch"
        matrix.append({
            "dimension": "Identity & Trademark",
            "requirement": f"Approved mark '{reference_info.get('name', 'Corporate')}'",
            "observed": obs,
            "outcome": "FAIL",
        })
    elif primary_cand and primary_cand.get("similarity_score", 0) >= 60.0:
        score = primary_cand.get("similarity_score", 0.0)
        matrix.append({
            "dimension": "Identity & Trademark",
            "requirement": "Approved reference template match (score >= 70%)",
            "observed": f"Verified match {score:.1f}% ({primary_cand.get('similarity_method', 'Template')})",
            "outcome": "PASS",
        })
    else:
        matrix.append({
            "dimension": "Identity & Trademark",
            "requirement": "Approved reference template match (score >= 70%)",
            "observed": "No confident match identified",
            "outcome": "FAIL" if candidates else "NOT EVALUATED",
        })

    # 2. Variant Conformity
    if not has_ref:
        matrix.append({
            "dimension": "Variant Conformity",
            "requirement": "Permitted brand variant specification",
            "observed": "No reference variant standard configured",
            "outcome": "NOT EVALUATED",
        })
    elif "UNAPPROVED_VARIANT" in findings_by_type:
        matrix.append({
            "dimension": "Variant Conformity",
            "requirement": f"Allowed: {reference_info.get('variant', 'PRIMARY')}",
            "observed": "Unapproved variant detected in artwork",
            "outcome": "FAIL",
        })
    elif primary_cand and primary_cand.get("matched_variant"):
        matrix.append({
            "dimension": "Variant Conformity",
            "requirement": f"Standard: {reference_info.get('variant', 'PRIMARY')}",
            "observed": f"Matches approved {primary_cand['matched_variant']}",
            "outcome": "PASS",
        })
    else:
        matrix.append({
            "dimension": "Variant Conformity",
            "requirement": "Approved variant conformances",
            "observed": "Variant could not be isolated",
            "outcome": "NOT EVALUATED",
        })

    # 3. Color Fidelity
    color_val = checks_summary.get("colour") or checks_summary.get("color_fidelity")
    if not has_ref:
        matrix.append({
            "dimension": "Color Fidelity",
            "requirement": "Palette compliance within delta-E tolerance",
            "observed": "No reference color standards configured",
            "outcome": "NOT EVALUATED",
        })
    elif "COLOUR_MISMATCH" in findings_by_type:
        f_list = findings_by_type["COLOUR_MISMATCH"]
        obs = f_list[0].get("observed_value", "Color deviation")
        matrix.append({
            "dimension": "Color Fidelity",
            "requirement": f"Approved palette (dE <= {std.get('color_delta_e_tolerance', 8.0)})",
            "observed": obs,
            "outcome": "FAIL",
        })
    elif _is_check_evaluated(color_val):
        passed = _is_check_passed(color_val)
        matrix.append({
            "dimension": "Color Fidelity",
            "requirement": f"Approved palette (dE <= {std.get('color_delta_e_tolerance', 8.0)})",
            "observed": "Palette verified within tolerance" if passed else "Color deviation detected",
            "outcome": "PASS" if passed else "FAIL",
        })
    else:
        matrix.append({
            "dimension": "Color Fidelity",
            "requirement": "Approved corporate color palette",
            "observed": "Color fidelity check not performed",
            "outcome": "NOT EVALUATED",
        })

    # 4. Aspect Ratio & Geometry
    if not has_ref:
        matrix.append({
            "dimension": "Aspect Ratio & Geometry",
            "requirement": "Proportional lock (+/- tolerance)",
            "observed": "Reference aspect ratio not configured",
            "outcome": "NOT EVALUATED",
        })
    elif "DISTORTION_DETECTED" in findings_by_type:
        f_list = findings_by_type["DISTORTION_DETECTED"]
        obs = f_list[0].get("observed_value", "Ratio mismatch")
        matrix.append({
            "dimension": "Aspect Ratio & Geometry",
            "requirement": f"Ratio: {reference_info.get('aspect_ratio', 1.0):.2f} (tol {std.get('aspect_ratio_tolerance', 0.05):.2f})",
            "observed": obs,
            "outcome": "FAIL",
        })
    elif primary_cand and "detected_aspect_ratio" in primary_cand:
        det_ar = primary_cand["detected_aspect_ratio"]
        exp_ar = reference_info.get("aspect_ratio", det_ar)
        tol = std.get("aspect_ratio_tolerance", 0.05)
        is_geom_pass = abs(det_ar - exp_ar) <= (exp_ar * tol + 0.01)
        matrix.append({
            "dimension": "Aspect Ratio & Geometry",
            "requirement": f"Ratio {exp_ar:.2f} (tol +/-{int(tol*100)}%)",
            "observed": f"Detected ratio {det_ar:.2f} (deviation {abs(det_ar-exp_ar)/exp_ar*100:.1f}%)",
            "outcome": "PASS" if is_geom_pass else "FAIL",
        })
    else:
        matrix.append({
            "dimension": "Aspect Ratio & Geometry",
            "requirement": "Aspect ratio conformity",
            "observed": "Geometric check not evaluated",
            "outcome": "NOT EVALUATED",
        })

    # 5. Minimum Display Size
    if not has_ref:
        matrix.append({
            "dimension": "Minimum Display Size",
            "requirement": "Legibility threshold (px / pt / mm)",
            "observed": "No size standard configured",
            "outcome": "NOT EVALUATED",
        })
    elif "LOGO_TOO_SMALL" in findings_by_type:
        f_list = findings_by_type["LOGO_TOO_SMALL"]
        obs = f_list[0].get("observed_value", "Undersized mark")
        matrix.append({
            "dimension": "Minimum Display Size",
            "requirement": f"Min: {std.get('min_width_px', 60)}x{std.get('min_height_px', 20)} px",
            "observed": obs,
            "outcome": "FAIL",
        })
    elif primary_cand and primary_cand.get("bounding_box_json"):
        try:
            bbox = json.loads(primary_cand["bounding_box_json"])
            w, h = bbox.get("width", 0), bbox.get("height", 0)
            mw = std.get("min_width_px", 60)
            mh = std.get("min_height_px", 20)
            is_size_ok = (w >= mw) and (h >= mh)
            matrix.append({
                "dimension": "Minimum Display Size",
                "requirement": f"Min: {mw}x{mh} px (pt: {std.get('min_width_pt', 50.0):.0f})",
                "observed": f"Rendered size: {w}x{h} px",
                "outcome": "PASS" if is_size_ok else "FAIL",
            })
        except Exception:
            matrix.append({
                "dimension": "Minimum Display Size",
                "requirement": "Minimum legibility threshold",
                "observed": "Dimensions not readable",
                "outcome": "NOT EVALUATED",
            })
    else:
        matrix.append({
            "dimension": "Minimum Display Size",
            "requirement": "Minimum display size",
            "observed": "Size check not evaluated",
            "outcome": "NOT EVALUATED",
        })

    # 6. Clearspace Protection
    cs_val = checks_summary.get("clearspace")
    if not has_ref:
        matrix.append({
            "dimension": "Clearspace Protection",
            "requirement": "Perimeter exclusion buffer",
            "observed": "No clearspace standard configured",
            "outcome": "NOT EVALUATED",
        })
    elif "CLEARSPACE_VIOLATION" in findings_by_type:
        f_list = findings_by_type["CLEARSPACE_VIOLATION"]
        obs = f_list[0].get("observed_value", "Intrusion detected")
        matrix.append({
            "dimension": "Clearspace Protection",
            "requirement": f"Buffer ratio >= {std.get('min_clearspace_ratio', 0.5):.1f}x",
            "observed": obs,
            "outcome": "FAIL",
        })
    elif _is_check_evaluated(cs_val):
        passed = _is_check_passed(cs_val)
        matrix.append({
            "dimension": "Clearspace Protection",
            "requirement": f"Buffer ratio >= {std.get('min_clearspace_ratio', 0.5):.1f}x",
            "observed": "Exclusion zone free of text and graphics" if passed else "Clearspace intrusion detected",
            "outcome": "PASS" if passed else "FAIL",
        })
    else:
        matrix.append({
            "dimension": "Clearspace Protection",
            "requirement": "Clearspace perimeter isolation",
            "observed": "Clearspace check not evaluated",
            "outcome": "NOT EVALUATED",
        })

    # 7. Page Quadrant / Placement
    if not has_ref:
        matrix.append({
            "dimension": "Page Placement & Quadrant",
            "requirement": "Approved layout position",
            "observed": "No placement standard configured",
            "outcome": "NOT EVALUATED",
        })
    elif "PLACEMENT_VIOLATION" in findings_by_type:
        f_list = findings_by_type["PLACEMENT_VIOLATION"]
        obs = f_list[0].get("observed_value", "Invalid quadrant")
        matrix.append({
            "dimension": "Page Placement & Quadrant",
            "requirement": f"Permitted: {', '.join(std.get('permitted_quadrants', ['ALL']))}",
            "observed": obs,
            "outcome": "FAIL",
        })
    elif primary_cand:
        quads = std.get("permitted_quadrants", ["ALL"])
        req_str = "Permitted: ALL" if "ALL" in quads else f"Permitted: {', '.join(quads)}"
        matrix.append({
            "dimension": "Page Placement & Quadrant",
            "requirement": req_str,
            "observed": "Position conforms to layout policy",
            "outcome": "PASS",
        })
    else:
        matrix.append({
            "dimension": "Page Placement & Quadrant",
            "requirement": "Approved page quadrant",
            "observed": "Placement check not evaluated",
            "outcome": "NOT EVALUATED",
        })

    # 8. Cropping & Boundary Integrity
    if not has_ref:
        matrix.append({
            "dimension": "Cropping & Boundary Integrity",
            "requirement": "Complete, unclipped visual presentation",
            "observed": "No boundary standard configured",
            "outcome": "NOT EVALUATED",
        })
    elif "CROPPED_OR_OBSTRUCTED_LOGO" in findings_by_type:
        f_list = findings_by_type["CROPPED_OR_OBSTRUCTED_LOGO"]
        obs = f_list[0].get("observed_value", "Clipped boundary")
        matrix.append({
            "dimension": "Cropping & Boundary Integrity",
            "requirement": "100% visible, unclipped outer boundary",
            "observed": obs,
            "outcome": "FAIL",
        })
    elif primary_cand:
        matrix.append({
            "dimension": "Cropping & Boundary Integrity",
            "requirement": "Complete, unclipped outer boundary",
            "observed": "No perimeter clipping or obstruction detected",
            "outcome": "PASS",
        })
    else:
        matrix.append({
            "dimension": "Cropping & Boundary Integrity",
            "requirement": "Complete visual presentation",
            "observed": "Boundary check not evaluated",
            "outcome": "NOT EVALUATED",
        })

    return matrix


