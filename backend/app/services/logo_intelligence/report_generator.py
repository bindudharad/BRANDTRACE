# Numbered Canvas for Running Headers, Footers & Checksum Proofs
# -----------------------------------------------------------------------------
class NumberedVerificationCanvas(canvas.Canvas):
    """
    Two-pass canvas that computes total page count dynamically and renders
    running enterprise headers, page numbers ('Page X of Y'), and the statutory
    BRANDTRACE governance disclaimer on every page.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states: List[Dict[str, Any]] = []
        self.report_number: str = "BT-RPT-UNKNOWN"
        self.report_id: str = ""
        self.issued_date: str = ""
        self.checksum_preview: str = ""

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()

        # Running header on subsequent pages (page 2+)
        if self._pageNumber > 1:
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(SLATE_MUTED)
            self.drawString(MARGIN, PAGE_HEIGHT - 26, "BRANDTRACE OFFICIAL LOGO VERIFICATION REPORT")
            self.setFont("Helvetica", 8)
            self.drawRightString(PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 26, f"REPORT: {self.report_number}")

            self.setStrokeColor(BORDER_COLOR)
            self.setLineWidth(0.6)
            self.line(MARGIN, PAGE_HEIGHT - 30, PAGE_WIDTH - MARGIN, PAGE_HEIGHT - 30)

        # Running footer on every page
        self.setStrokeColor(BORDER_COLOR)
        self.setLineWidth(0.6)
        self.line(MARGIN, 40, PAGE_WIDTH - MARGIN, 40)

        # Disclaimer
        disclaimer = (
            "Generated by BRANDTRACE — Evidence-Based Brand Governance. "
            "This report documents visual brand compliance evaluated against registered reference assets and brand rules. "
            "It does not replace legal trademark certification."
        )
        self.setFont("Helvetica", 6.8)
        self.setFillColor(SLATE_MUTED)
        self.drawString(MARGIN, 28, disclaimer)

        # Metadata line
        meta_str = f"Report ID: {self.report_id}  |  Issued: {self.issued_date}  |  Integrity SHA-256: {self.checksum_preview}"
        self.setFont("Helvetica", 6.8)
        self.setFillColor(SLATE_LIGHT)
        self.drawString(MARGIN, 16, meta_str)

        # Page Number
        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.setFont("Helvetica-Bold", 7.5)
        self.setFillColor(NAVY_PRIMARY)
        self.drawRightString(PAGE_WIDTH - MARGIN, 16, page_str)

        self.restoreState()


